"""Generate the report's tables and inline numbers from ``results/``.

The original version of this project put its headline numbers into the README and
the LaTeX report by hand. They then drifted from the code, and one of them --
copied out of a notebook that hardcoded its weights -- was never reproducible at
all. Hand-transcription is the mechanism by which a paper and its data diverge.

So neither the report nor the README contains numbers. They contain ``\\input``
directives, macros, and a delimited block, all written by this script from
``results/metrics.csv`` and ``results/significance.csv``. If the experiment is
re-run and a conclusion changes, the prose changes with it or fails to build.

    python experiments/make_report_tables.py
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

BENCHMARK = "equal_weight"
README_START = "<!-- RESULTS:START -->"
README_END = "<!-- RESULTS:END -->"

PRETTY = {
    "equal_weight": r"1/N (benchmark)",
    "sample": "Sample",
    "ledoit_wolf": "Ledoit--Wolf",
    "bayes_stein": "Bayes--Stein",
    "niw_predictive": "NIW predictive",
    "black_litterman": "Black--Litterman",
    "min_variance": "Min-var",
    "convex": "Convex",
    "gp_bayesopt": "GP BayesOpt",
}


def label(name: str) -> str:
    if name == BENCHMARK:
        return PRETTY[BENCHMARK]
    estimator, allocator = name.split("+")
    return f"{PRETTY.get(estimator, estimator)} + {PRETTY.get(allocator, allocator)}"


def metrics_table(metrics: pd.DataFrame) -> str:
    rows = []
    for name, row in metrics.iterrows():
        bold = r"\bfseries " if name == BENCHMARK else ""
        rows.append(
            f"{bold}{label(name)} & {row['sharpe']:.3f} & {row['ann_return']:.2%} & "
            f"{row['ann_vol']:.2%} & {row['max_drawdown']:.2%} & "
            f"{row['avg_turnover']:.3f} \\\\".replace("%", r"\%")
        )
    body = "\n".join(rows)
    return f"""% Generated by experiments/make_report_tables.py -- do not edit.
\\begin{{tabular}}{{@{{}}lrrrrr@{{}}}}
\\toprule
\\textbf{{Strategy}} & \\textbf{{Sharpe}} & \\textbf{{Ann.\\ ret.}} & \\textbf{{Ann.\\ vol.}} &
\\textbf{{Max DD}} & \\textbf{{Turnover}} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
"""


def significance_table(inference: pd.DataFrame) -> str:
    rows = []
    for name, row in inference.iterrows():
        if name == BENCHMARK:
            rows.append(
                f"\\bfseries {label(name)} & {row['sharpe']:.3f} & "
                f"[{row['sharpe_ci_low']:.2f}, {row['sharpe_ci_high']:.2f}] & "
                f"--- & --- & {row['deflated_sharpe']:.3f} \\\\"
            )
            continue
        rows.append(
            f"{label(name)} & {row['sharpe']:.3f} & "
            f"[{row['sharpe_ci_low']:.2f}, {row['sharpe_ci_high']:.2f}] & "
            f"{row['sharpe_vs_benchmark']:+.3f} & {row['p_ledoit_wolf']:.3f} & "
            f"{row['deflated_sharpe']:.3f} \\\\"
        )
    body = "\n".join(rows)
    return f"""% Generated by experiments/make_report_tables.py -- do not edit.
\\begin{{tabular}}{{@{{}}lrcrrr@{{}}}}
\\toprule
\\textbf{{Strategy}} & \\textbf{{Sharpe}} & \\textbf{{95\\% CI}} &
\\textbf{{$\\Delta$ vs 1/N}} & \\textbf{{$p$}} & \\textbf{{DSR}} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
"""


def macros(metrics: pd.DataFrame, inference: pd.DataFrame, config: dict) -> str:
    """Inline numbers, so no figure in the prose is ever typed by hand."""
    best = metrics.index[0]
    bench = metrics.loc[BENCHMARK]
    p_values = inference["p_ledoit_wolf"].dropna()
    n_beating = int((p_values < 0.05).sum())

    convex = [n for n in metrics.index if n.endswith("+convex")]
    gp = [n for n in metrics.index if n.endswith("+gp_bayesopt")]

    sharpe_spread = metrics["sharpe"].max() - metrics["sharpe"].min()
    bench_ci_width = (inference.loc[BENCHMARK, "sharpe_ci_high"]
                      - inference.loc[BENCHMARK, "sharpe_ci_low"])

    # Signed: replacing convex with GP search moves mean Sharpe by this much.
    convex_mean = metrics.loc[convex, "sharpe"].mean()
    gp_mean = metrics.loc[gp, "sharpe"].mean()
    optimiser_delta = gp_mean - convex_mean

    # The v1 abstract's claim, restated as an absolute Sharpe gap, against the
    # like-for-like gap measured here on the same two arms (sample moments,
    # convex vs GP). Quoting "N times larger" in prose without deriving it is how
    # the previous version of this paper got its numbers wrong.
    v1_claimed_gap = 1.312 - 0.969
    measured_arm_gap = (metrics.loc["sample+gp_bayesopt", "sharpe"]
                        - metrics.loc["sample+convex", "sharpe"])

    entries = {
        "oosPeriods": str(config["oos_periods"]),
        "oosStart": config["oos_start"],
        "oosEnd": config["oos_end"],
        "nTrials": str(config["n_trials_for_dsr"]),
        "nAssets": str(len(config["panel"]["assets"])),
        "trainWindow": str(config["walk_forward"]["train_window"]),
        "rebalanceEvery": str(config["walk_forward"]["rebalance_every"]),
        "costBps": f"{config['walk_forward']['cost_bps']:.0f}",
        "maxWeight": f"{config['walk_forward']['max_weight']:.0%}".replace("%", r"\%"),
        "gpBudget": str(config["search_budget"]["gp"]),
        "benchSharpe": f"{bench['sharpe']:.3f}",
        "benchReturn": f"{bench['ann_return']:.2%}".replace("%", r"\%"),
        "benchDrawdown": f"{bench['max_drawdown']:.2%}".replace("%", r"\%"),
        "benchTurnover": f"{bench['avg_turnover']:.3f}",
        "bestName": label(best),
        "bestSharpe": f"{metrics.loc[best, 'sharpe']:.3f}",
        "bestSharpeGap": f"{metrics.loc[best, 'sharpe'] - bench['sharpe']:+.3f}",
        "bestPValue": f"{inference.loc[best, 'p_ledoit_wolf']:.3f}",
        "nBeatingBenchmark": str(n_beating),
        "nStrategies": str(len(metrics) - 1),
        "sharpeSpread": f"{metrics['sharpe'].max() - metrics['sharpe'].min():.3f}",
        "convexMeanSharpe": f"{convex_mean:.3f}",
        "gpMeanSharpe": f"{gp_mean:.3f}",
        "optimiserGap": f"{abs(optimiser_delta):.3f}",
        "optimiserDelta": f"{optimiser_delta:+.3f}",
        "claimRatio": f"{abs(v1_claimed_gap / measured_arm_gap):.1f}",
        "convexTurnover": f"{metrics.loc[convex, 'avg_turnover'].mean():.3f}",
        "gpTurnover": f"{metrics.loc[gp, 'avg_turnover'].mean():.3f}",
        "widestCI": f"{(inference['sharpe_ci_high'] - inference['sharpe_ci_low']).max():.2f}",
        "medianCI": f"{(inference['sharpe_ci_high'] - inference['sharpe_ci_low']).median():.2f}",
        "benchCILow": f"{inference.loc[BENCHMARK, 'sharpe_ci_low']:.2f}",
        "benchCIHigh": f"{inference.loc[BENCHMARK, 'sharpe_ci_high']:.2f}",
        "benchCIWidth": f"{bench_ci_width:.2f}",
        # How many times wider the benchmark's own interval is than the entire
        # best-to-worst spread of the study. Prose must not assert this by hand.
        "ciSpreadRatio": f"{bench_ci_width / sharpe_spread:.1f}",
    }

    lines = ["% Generated by experiments/make_report_tables.py -- do not edit."]
    lines += [f"\\newcommand{{\\{key}}}{{{value}}}" for key, value in entries.items()]
    return "\n".join(lines) + "\n"


def readme_section(metrics: pd.DataFrame, inference: pd.DataFrame, config: dict) -> str:
    """The README's results block. Same source of truth as the paper's tables."""
    joined = metrics.join(
        inference[["sharpe_ci_low", "sharpe_ci_high", "sharpe_vs_benchmark",
                   "p_ledoit_wolf", "deflated_sharpe"]]
    ).sort_values("sharpe", ascending=False)

    bench = joined.loc[BENCHMARK]
    convex = [n for n in joined.index if n.endswith("+convex")]
    gp = [n for n in joined.index if n.endswith("+gp_bayesopt")]
    estimators = [n.split("+")[0] for n in convex]

    # Paired comparison: same estimator, same feasible set, different optimiser.
    gp_losses = sum(
        joined.loc[f"{e}+convex", "sharpe"] > joined.loc[f"{e}+gp_bayesopt", "sharpe"]
        for e in estimators
    )
    convex_mean = joined.loc[convex, "sharpe"].mean()
    gp_mean = joined.loc[gp, "sharpe"].mean()

    p_values = joined["p_ledoit_wolf"].dropna()
    n_beating = int((p_values < 0.05).sum())
    n_strategies = len(joined) - 1

    ci_width = (joined["sharpe_ci_high"] - joined["sharpe_ci_low"]).median()
    estimator_spread = joined.loc[convex, "sharpe"].max() - joined.loc[convex, "sharpe"].min()
    optimiser_gap = convex_mean - gp_mean

    rows = []
    for name, row in joined.iterrows():
        mark = "**" if name == BENCHMARK else ""
        if name == BENCHMARK:
            delta, pval = "—", "—"
        else:
            delta, pval = f"{row['sharpe_vs_benchmark']:+.3f}", f"{row['p_ledoit_wolf']:.2f}"
        rows.append(
            f"| {mark}{label(name).replace('--', '–')}{mark} | {mark}{row['sharpe']:.3f}{mark} | "
            f"[{row['sharpe_ci_low']:.2f}, {row['sharpe_ci_high']:.2f}] | {delta} | {pval} | "
            f"{row['ann_return']:.2%} | {row['max_drawdown']:.2%} | {row['avg_turnover']:.2f} |"
        )
    table = "\n".join(rows)

    wf = config["walk_forward"]
    return f"""{README_START}
<!-- Generated by experiments/make_report_tables.py -- do not edit by hand. -->

## Results

{config['oos_periods']} out-of-sample weeks ({config['oos_start']} → {config['oos_end']}),
{len(config['panel']['assets'])} assets, {wf['train_window']}-week rolling training window,
rebalanced every {wf['rebalance_every']} weeks, {wf['cost_bps']:.0f} bps proportional cost,
{wf['max_weight']:.0%} position cap. Every weight is chosen using only data strictly
preceding the period it is evaluated on.

| Strategy | Sharpe | 95% CI | Δ vs 1/N | *p* | Ann. return | Max DD | Turnover |
|---|---|---|---|---|---|---|---|
{table}

*p* is the Ledoit–Wolf (2008) test for a difference in Sharpe ratios against 1/N,
robust to the autocorrelation and fat tails that invalidate the textbook
Jobson–Korkie statistic. Intervals are stationary-bootstrap percentiles.

### What the experiment found

**1. Bayesian optimisation lost to convex optimisation — on every estimator.**
Given the identical objective, the identical feasible set, and a search budget that
*favoured* it ({config['search_budget']['gp']} GP evaluations against
{config['search_budget']['convex_restarts']} SLSQP restarts), the Gaussian-process
allocator finished behind SLSQP in {gp_losses} of {len(estimators)} paired
comparisons — mean Sharpe {gp_mean:.3f} against {convex_mean:.3f}, a gap of
{optimiser_gap:.3f}. It also turned over
{joined.loc[gp, 'avg_turnover'].mean() / joined.loc[convex, 'avg_turnover'].mean():.1f}×
as much portfolio per rebalance to get there.

This is the reverse of what the original version of this project reported, and the
reversal is diagnostic rather than surprising. Maximising the Sharpe ratio of a
plug-in `μ`/`Σ` is a *convex* problem that SLSQP solves essentially exactly. A
global black-box search cannot beat an exact solver on its own objective; it can
only fit the training window's noise more aggressively. In-sample that looks like
outperformance. Out-of-sample it is a cost.

**2. Nothing beat 1/N. Not one strategy of {n_strategies}.**
The best configuration ({label(joined.index[0]).replace('--', '–')}, Sharpe
{joined.iloc[0]['sharpe']:.3f}) sits {joined.iloc[0]['sharpe_vs_benchmark']:+.3f}
above the benchmark with *p* = {joined.iloc[0]['p_ledoit_wolf']:.2f} — it pays for
that edge with {joined.iloc[0]['max_drawdown']:.1%} maximum drawdown against 1/N's
{bench['max_drawdown']:.1%}, and {joined.iloc[0]['avg_turnover'] / bench['avg_turnover']:.0f}×
the turnover. {n_beating} of {n_strategies} configurations beat equal-weighting at
the 5% level. This replicates [DeMiguel, Garlappi & Uppal (2009)](https://doi.org/10.1093/rfs/hhm075)
on an independent sample.

**3. The estimator axis was nearly flat here — and the error bars explain why.**
Across the convex allocators, swapping sample moments for Ledoit–Wolf, Bayes–Stein,
NIW, or Black–Litterman moved the Sharpe ratio by {estimator_spread:.3f} in total.
The median 95% interval is {ci_width:.2f} Sharpe units wide. With
{config['oos_periods']} weekly observations, *no* difference of the size this
literature typically reports is distinguishable from zero.

That is the finding with teeth, and it indicts the original claim directly: a
"35% Sharpe improvement" is roughly {0.35 * bench['sharpe'] / ci_width:.2f} of one
confidence-interval width. It was never a result. It was noise that had not been
measured.

Read this as a negative result on a small universe, not a general law: with
{len(config['panel']['assets'])} assets and a {wf['train_window']}-week window,
`N/T` is small, which is exactly the regime where shrinkage has least to offer.
The design, not the verdict, is what transfers.

<p align="center">
  <img src="results/figures/equity_curves.png" width="88%" alt="Out-of-sample equity curves">
  <br><em>Out-of-sample growth of $1. The spread between methods is smaller than the
  spread between plausible histories of any one of them.</em>
</p>

<p align="center">
  <img src="results/figures/sharpe_intervals.png" width="88%" alt="Sharpe ratios with bootstrap confidence intervals">
  <br><em>Every interval contains every other point estimate. Overlap alone does not
  settle it — these series are highly correlated, so the paired difference test is
  what governs. Here it agrees.</em>
</p>

{README_END}"""


def postmortem_section(metrics: pd.DataFrame, inference: pd.DataFrame, config: dict) -> str:
    """The claimed-vs-corrected comparison, on the arms the original actually compared.

    The v1 "naive" arm was a convex max-Sharpe solve on sample moments; the v1
    "Bayesian" arm was ``gp_minimize`` on the same sample moments. Those map onto
    ``sample+convex`` and ``sample+gp_bayesopt``, so the original experiment can be
    re-run honestly rather than merely criticised.
    """
    naive, bayes = "sample+convex", "sample+gp_bayesopt"
    n = metrics.loc[naive]
    b = metrics.loc[bayes]
    sharpe_delta = (b["sharpe"] - n["sharpe"]) / n["sharpe"]
    dd_delta = (abs(b["max_drawdown"]) - abs(n["max_drawdown"])) / abs(n["max_drawdown"])
    bench = metrics.loc[BENCHMARK]

    return f"""{README_START}
<!-- Generated by experiments/make_report_tables.py -- do not edit by hand. -->

The original experiment compared a convex max-Sharpe solve on sample moments
against `gp_minimize` on the same sample moments. In this codebase those are
`sample+convex` and `sample+gp_bayesopt`. Re-running that exact comparison
out-of-sample, on the same asset panel, with a shared feasible set:

| | v1 claim (in-sample) | corrected (walk-forward) |
|---|---|---|
| Naive Sharpe | 0.969 | {n['sharpe']:.3f} |
| "Bayesian" Sharpe | 1.312 | {b['sharpe']:.3f} |
| **Sharpe change** | **+35%** | **{sharpe_delta:+.1%}** |
| Naive max drawdown | -25.56% | {n['max_drawdown']:.2%} |
| "Bayesian" max drawdown | -16.89% | {b['max_drawdown']:.2%} |
| **Drawdown change** | **-34%** | **{dd_delta:+.1%}** |

**The sign of the headline result reverses.** Bayesian optimisation does not
improve the Sharpe ratio by 35%; it *reduces* it by {abs(sharpe_delta):.0%} once the
weights are chosen without seeing the evaluation window. The drawdown reduction
survives in direction only, at {abs(dd_delta):.0%} rather than 34%, and is far
inside the noise.

Widening to the full {len(metrics) - 1}-configuration grid: the best strategy
reached a Sharpe of {metrics['sharpe'].max():.3f} against {bench['sharpe']:.3f} for
1/N, and **{int((inference['p_ledoit_wolf'].dropna() < 0.05).sum())} of
{len(metrics) - 1}** configurations beat equal-weighting at the 5% level. The
median 95% confidence interval is
{(inference['sharpe_ci_high'] - inference['sharpe_ci_low']).median():.2f} Sharpe
units wide — several times the size of the effect originally claimed. The v1
number was not merely wrong in magnitude; it was reported at a precision the data
could never have supported.

Full table and discussion in the [README](../README.md#results).

{README_END}"""


def update_readme(readme: Path, section: str) -> bool:
    text = readme.read_text(encoding="utf-8")
    pattern = re.compile(
        re.escape(README_START) + ".*?" + re.escape(README_END), re.DOTALL
    )
    if pattern.search(text):
        updated = pattern.sub(lambda _: section, text)
    elif "<!-- RESULTS -->" in text:
        updated = text.replace("<!-- RESULTS -->", section)
    else:
        raise SystemExit(
            f"{readme} has no {README_START}/{README_END} block to fill. "
            "Add the markers where the results should go."
        )
    if updated == text:
        return False
    readme.write_text(updated, encoding="utf-8")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    root = Path(__file__).resolve().parent.parent
    parser.add_argument("--results", type=Path, default=root / "results")
    parser.add_argument("--outdir", type=Path, default=root / "reports" / "LaTeX" / "generated")
    parser.add_argument("--readme", type=Path, default=root / "README.md")
    parser.add_argument("--postmortem", type=Path, default=root / "docs" / "postmortem.md")
    args = parser.parse_args()

    metrics = pd.read_csv(args.results / "metrics.csv", index_col=0)
    inference = pd.read_csv(args.results / "significance.csv", index_col=0)
    config = json.loads((args.results / "config.json").read_text(encoding="utf-8"))

    args.outdir.mkdir(parents=True, exist_ok=True)
    written = {
        "metrics_table.tex": metrics_table(metrics),
        "significance_table.tex": significance_table(inference),
        "macros.tex": macros(metrics, inference, config),
    }
    for filename, content in written.items():
        (args.outdir / filename).write_text(content, encoding="utf-8")
        print(f"  wrote {args.outdir / filename}")

    for path, builder in (
        (args.readme, readme_section),
        (args.postmortem, postmortem_section),
    ):
        changed = update_readme(path, builder(metrics, inference, config))
        print(f"  {'updated' if changed else 'unchanged'} {path}")

    print(f"\n{len(written)} files generated from {args.results}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
